// Builds Marinduque boundaries from the HDX COD-AB Philippines shapefiles (NAMRIA/PSA, CC BY-IGO).
//
// Dataset page: https://data.humdata.org/dataset/cod-ab-phl (phl_admin_boundaries.shp.zip, about 900 MB).
// Only needed to regenerate the outputs below, which are kept in the repo.
//
// Usage: npx tsx scripts/build-boundaries.ts <folder containing phl_admin3.shp and phl_admin4.shp>
//
// Writes:
//   public/boundaries/{province,municipalities,barangays}.geojson   for the map
//   supabase/migrations/0003_boundaries.sql                         polygons and the barangay list
import { spawnSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const SIMPLIFY_METRES = 20;
const COORDINATE_PRECISION = 0.00001; // about 1 m
const OUT_DIR = 'public/boundaries';
const MIGRATION = 'supabase/migrations/0003_boundaries.sql';
const EXPECTED_MUNICIPALITIES = ['Boac', 'Buenavista', 'Gasan', 'Mogpog', 'Santa Cruz', 'Torrijos'];

const sourceDir = process.argv[2];
if (!sourceDir) {
  console.error('Usage: npx tsx scripts/build-boundaries.ts <folder with phl_admin3.shp and phl_admin4.shp>');
  process.exit(1);
}

mkdirSync(OUT_DIR, { recursive: true });

function mapshaper(args: string[]) {
  const cli = join('node_modules', 'mapshaper', 'bin', 'mapshaper');
  const result = spawnSync(process.execPath, ['--max-old-space-size=8192', cli, ...args], { encoding: 'utf8' });
  if (result.status !== 0) throw new Error(result.stderr || `mapshaper exited with ${result.status}`);
  process.stderr.write(result.stderr);
}

function extract(layer: 'admin3' | 'admin4', fields: string, output: string, extra: string[] = []) {
  mapshaper([
    join(sourceDir, `phl_${layer}.shp`),
    '-filter', "adm2_name === 'Marinduque'",
    '-simplify', 'dp', `interval=${SIMPLIFY_METRES}`, 'keep-shapes',
    '-clean',
    '-filter-fields', fields,
    ...extra,
    '-o', output, 'format=geojson', `precision=${COORDINATE_PRECISION}`,
  ]);
}

const municipalitiesPath = join(OUT_DIR, 'municipalities.geojson');
const barangaysPath = join(OUT_DIR, 'barangays.geojson');
const provincePath = join(OUT_DIR, 'province.geojson');

// The source names the capital "Boac (Capital)"; the app and the report use "Boac".
extract('admin3', 'adm3_name,adm3_pcode', municipalitiesPath, [
  '-each', "adm3_name = adm3_name.replace(' (Capital)', '')",
]);
extract('admin4', 'adm3_pcode,adm4_name,adm4_pcode', barangaysPath);
mapshaper([municipalitiesPath, '-dissolve', '-o', provincePath, 'format=geojson', `precision=${COORDINATE_PRECISION}`]);

interface Feature {
  properties: Record<string, string>;
  geometry: { type: 'Polygon' | 'MultiPolygon'; coordinates: unknown };
}

const read = (path: string): Feature[] => JSON.parse(readFileSync(path, 'utf8')).features;
const quote = (text: string) => `'${text.replaceAll("'", "''")}'`;
const multiPolygon = (feature: Feature) =>
  `ST_Multi(ST_SetSRID(ST_GeomFromGeoJSON(${quote(JSON.stringify(feature.geometry))}), 4326))`;

const municipalities = read(municipalitiesPath);
const barangays = read(barangaysPath);

// A name that doesn't match the lookup would silently leave a municipality without a polygon.
const names = municipalities.map((m) => m.properties.adm3_name).sort().join(', ');
if (names !== EXPECTED_MUNICIPALITIES.join(', ')) {
  throw new Error(`Municipality names don't match the lookup: ${names}`);
}

const sql = [
  '-- Generated by scripts/build-boundaries.ts. Do not edit by hand.',
  '-- Source: HDX COD-AB Philippines (NAMRIA, PSA), CC BY-IGO.',
  '',
  ...municipalities.map(
    (m) =>
      `update public.municipalities set psgc_code = ${quote(m.properties.adm3_pcode)}, boundary = ${multiPolygon(m)} ` +
      `where name = ${quote(m.properties.adm3_name)};`,
  ),
  '',
  ...barangays.map(
    (b) =>
      'insert into public.barangays (municipality_id, name, psgc_code, boundary) values (' +
      `(select id from public.municipalities where psgc_code = ${quote(b.properties.adm3_pcode)}), ` +
      `${quote(b.properties.adm4_name)}, ${quote(b.properties.adm4_pcode)}, ${multiPolygon(b)});`,
  ),
  '',
].join('\n');

writeFileSync(MIGRATION, sql);

console.log('Municipalities:', municipalities.map((m) => m.properties.adm3_name).join(', '));
console.log('Barangays:', barangays.length);
