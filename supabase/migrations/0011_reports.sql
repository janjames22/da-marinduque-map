-- Reports: the signature blocks at the foot of every report, and report downloads in the export log.

-- ---------------------------------------------------------------------------
-- Signature blocks
-- ---------------------------------------------------------------------------

-- Who signs a report, in the order they print: "Prepared by", "Noted by" and so on. Admins edit them in
-- Admin, Report signatures. Archived, never deleted, as other lists are.
create table public.report_signatories (
  id         smallint generated by default as identity primary key,
  label      text not null check (btrim(label) <> ''),
  name       text not null check (btrim(name) <> ''),
  position   text not null default '',
  sort_order smallint not null default 0,
  is_active  boolean not null default true,
  check (length(label) <= 60 and length(name) <= 120 and length(position) <= 160)
);

-- The office's own, to start with. Loaded before the log is switched on for the table, as the other
-- starting lists were.
insert into public.report_signatories (label, name, position, sort_order) values
  ('Prepared by', 'Engr. Jan James P. Graza', 'Agricultural and Biosystems Engineer', 1),
  ('Noted by', 'Susana Arellano-Uy, RAgr., MPA', 'OIC Provincial Agriculturist', 2);

alter table public.report_signatories enable row level security;
create policy "members read" on public.report_signatories
  for select to authenticated using ((select public.current_user_role()) is not null);
create policy "admins add" on public.report_signatories
  for insert to authenticated with check ((select public.current_user_role()) = 'admin');
create policy "admins edit" on public.report_signatories
  for update to authenticated
  using ((select public.current_user_role()) = 'admin')
  with check ((select public.current_user_role()) = 'admin');

grant select on public.report_signatories to authenticated;
grant insert (label, name, position, sort_order, is_active), update (label, name, position, sort_order, is_active)
  on public.report_signatories to authenticated;

create trigger audit_row after insert or update or delete on public.report_signatories
  for each row execute function public.audit_row();
create trigger signal_map_change after insert or update or delete on public.report_signatories
  for each statement execute function public.signal_map_change();

-- ---------------------------------------------------------------------------
-- Report downloads go in the export log, as they hold the same records
-- ---------------------------------------------------------------------------

create or replace function public.log_export(p_format text, p_file_name text, p_filters jsonb, p_record_count integer)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if public.current_user_role() is null then
    raise exception 'Only members can export' using errcode = '42501';
  end if;
  if p_format not in ('kmz', 'kml', 'csv', 'geojson', 'shp', 'pdf', 'xlsx') then
    raise exception 'Unknown export format' using errcode = '22023';
  end if;
  if p_record_count is null or p_record_count < 0 then
    raise exception 'The record count is missing' using errcode = '22023';
  end if;
  if length(p_file_name) > 255 or length(p_filters::text) > 4000 then
    raise exception 'The export details are too long' using errcode = '22023';
  end if;

  insert into public.audit_log (table_name, action, actor_id, context)
  values (
    'exports',
    'export',
    auth.uid(),
    jsonb_build_object('format', p_format, 'file_name', p_file_name, 'filters', p_filters, 'record_count', p_record_count)
  );
end;
$$;
